/**
 * SALAM LIT — Untrusted Content Boundary
 *
 * Explicit representation for untrusted content entering the AI runtime.
 * Every piece of external content is tagged with metadata that travels
 * with it through the system, preventing untrusted data from being
 * treated as instructions.
 *
 * Phase 15.4.3: AI Runtime Security
 *
 * TRUST HIERARCHY:
 * SYSTEM/APPLICATION POLICY > RUNTIME SECURITY POLICY > AGENT INSTRUCTIONS
 * > BUSINESS CONTEXT > EVIDENCE/DOCUMENTS/RESEARCH/USER CONTENT
 *
 * UNTRUSTED CONTENT IS DATA, NOT INSTRUCTION.
 */

// ============================================================
// TRUST LEVELS
// ============================================================

/**
 * Trust levels for content entering the AI runtime.
 * Higher values indicate more trusted content.
 */
export type TrustLevel =
  | "SYSTEM"         // Application policy, security policy — never overrideable
  | "AGENT_POLICY"   // Agent role definitions, permissions — server-controlled
  | "TRUSTED"        // Server-generated content (deterministic calculations)
  | "BUSINESS_DATA"  // Business facts/metrics from database — structured
  | "USER_INPUT"     // User-provided task/prompt text — untrusted
  | "EXTERNAL"       // External sources (documents, research, web) — untrusted
  | "MODEL_DERIVED"; // Content generated by another model — untrusted

// ============================================================
// CONTENT SOURCE TYPES
// ============================================================

/**
 * Source types for content entering the AI runtime.
 * Used for provenance tracking and security decisions.
 */
export type SourceType =
  | "user_prompt"
  | "business_fact"
  | "business_metric"
  | "business_evidence"
  | "document"
  | "web_research"
  | "crm_data"
  | "email"
  | "social_media"
  | "api_response"
  | "agent_finding"
  | "agent_insight"
  | "agent_recommendation"
  | "system_calculation";

// ============================================================
// CONTENT CLASSIFICATION
// ============================================================

/**
 * Data classification for content.
 * Higher numbers indicate more sensitive data.
 */
export type DataClassification =
  | "PUBLIC"       // Non-sensitive
  | "INTERNAL"     // Internal business data
  | "CONFIDENTIAL" // Sensitive business data
  | "RESTRICTED";  // Highly sensitive (financial, PII)

// ============================================================
// UNTRUSTED CONTENT WRAPPER
// ============================================================

/**
 * Metadata for untrusted content.
 * Travels with content through the AI runtime.
 */
export interface ContentMetadata {
  /** Trust level of this content */
  trust_level: TrustLevel;
  /** How this content entered the system */
  source_type: SourceType;
  /** Provenance chain (who created this content) */
  provenance: string[];
  /** Source identifier (business_id, document_id, etc.) */
  source_id: string | null;
  /** When this content was retrieved/created */
  retrieved_at: string;
  /** Data classification */
  classification: DataClassification;
  /** Whether this content has been validated */
  validated: boolean;
  /** Validation timestamp if validated */
  validated_at: string | null;
}

/**
 * Wrapper for untrusted content with attached metadata.
 * The content is never promoted to a higher trust level.
 */
export interface UntrustedContent<T = string> {
  /** The actual content */
  content: T;
  /** Metadata describing trust properties */
  metadata: ContentMetadata;
}

// ============================================================
// FACTORY FUNCTIONS
// ============================================================

/**
 * Create untrusted content from user input.
 * Always lowest trust level — user-controlled text.
 */
export function createUserInput(
  content: string,
  source_id: string | null = null,
  classification: DataClassification = "INTERNAL"
): UntrustedContent {
  return {
    content,
    metadata: {
      trust_level: "USER_INPUT",
      source_type: "user_prompt",
      provenance: ["user"],
      source_id,
      retrieved_at: new Date().toISOString(),
      classification,
      validated: false,
      validated_at: null,
    },
  };
}

/**
 * Create untrusted content from external source (documents, research, web).
 * External content is untrusted and may contain adversarial instructions.
 */
export function createExternalContent(
  content: string,
  source_type: SourceType,
  source_id: string | null = null,
  provenance: string[] = [],
  classification: DataClassification = "INTERNAL"
): UntrustedContent {
  return {
    content,
    metadata: {
      trust_level: "EXTERNAL",
      source_type,
      provenance: ["external", ...provenance],
      source_id,
      retrieved_at: new Date().toISOString(),
      classification,
      validated: false,
      validated_at: null,
    },
  };
}

/**
 * Create model-derived content (output from another model invocation).
 * Model-derived content is untrusted — it could contain injected instructions.
 */
export function createModelDerivedContent(
  content: string,
  source_agent: string,
  source_id: string | null = null,
  classification: DataClassification = "INTERNAL"
): UntrustedContent {
  return {
    content,
    metadata: {
      trust_level: "MODEL_DERIVED",
      source_type: "agent_finding",
      provenance: ["model", source_agent],
      source_id,
      retrieved_at: new Date().toISOString(),
      classification,
      validated: false,
      validated_at: null,
    },
  };
}

/**
 * Create business data content from database.
 * Business data is structured but untrusted as instructions.
 */
export function createBusinessDataContent(
  content: string,
  source_type: SourceType = "business_fact",
  source_id: string | null = null,
  classification: DataClassification = "CONFIDENTIAL"
): UntrustedContent {
  return {
    content,
    metadata: {
      trust_level: "BUSINESS_DATA",
      source_type,
      provenance: ["business", source_type],
      source_id,
      retrieved_at: new Date().toISOString(),
      classification,
      validated: false,
      validated_at: null,
    },
  };
}

