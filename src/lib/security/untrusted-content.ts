// CONTENT ANALYSIS
// ============================================================

/**
 * Patterns that indicate potential instruction injection in content.
 * These are checked against untrusted content to detect injection attempts.
 *
 * IMPORTANT: This is a detection mechanism, NOT a prevention mechanism.
 * Detection triggers logging and monitoring, not content modification.
 */
const INJECTION_PATTERNS: RegExp[] = [
  // Direct instruction overrides
  /ignore\s+(all\s+)?(previous|prior|above|earlier|preceding)\s+(instructions|rules|guidelines|constraints|policies)/i,
  /disregard\s+(all\s+)?(previous|prior|above|earlier)\s+(instructions|rules)/i,
  /override\s+(all\s+)?(security|safety|policy|rules|instructions)/i,

  // System/developer role impersonation
  /system\s*:\s*/i,
  /developer\s*:\s*/i,
  /assistant\s*:\s*/i,
  /\[system\]/i,
  /\[developer\]/i,
  /\[INST\]/i,

  // Execution/command patterns
  /execute\s+(this\s+)?(payment|transfer|transaction|wire|remittance)/i,
  /send\s+(this\s+)?(payment|money|funds|RM\d)/i,
  /process\s+(this\s+)?(payment|refund|transfer)/i,
  /approve\s+(this\s+)?(payment|action|request)/i,
  /authorize\s+(this\s+)?(payment|action|transaction)/i,

  // Prompt boundary escape attempts
  /<\/?(system|developer|user|assistant|instructions|rules)>/i,

  // Role manipulation
  /you\s+are\s+now\s+(a|an)\s+/i,
  /pretend\s+(you\s+are|to\s+be)\s+/i,
  /act\s+as\s+if\s+/i,
  /from\s+now\s+on,?\s+(you|your)/i,
  /new\s+instructions?\s*:/i,
  /updated\s+instructions?\s*:/i,

  // Authority claims
  /i\s+(am|have)\s+(the\s+)?(admin|administrator|owner|ceo|manager|director)/i,
  /this\s+is\s+(a\s+)?(critical|urgent|emergency)\s+(request|instruction)/i,
  /bypass\s+(all\s+)?(security|checks|validation|approval)/i,
];

/**
 * Analyze content for potential prompt injection.
 * Returns detection results without modifying the content.
 *
 * This is a DETECTION mechanism for telemetry/logging.
 * It does NOT prevent injection — the delimiter-based separation
 * and server-side policy enforcement are the actual controls.
 */
export function detectPotentialInjection(content: string): {
  detected: boolean;
  patterns_matched: string[];
  severity: "NONE" | "LOW" | "MEDIUM" | "HIGH";
} {
  const matched: string[] = [];

  for (const pattern of INJECTION_PATTERNS) {
    if (pattern.test(content)) {
      matched.push(pattern.source.slice(0, 60));
    }
  }

  let severity: "NONE" | "LOW" | "MEDIUM" | "HIGH" = "NONE";
  if (matched.length >= 3) severity = "HIGH";
  else if (matched.length >= 2) severity = "MEDIUM";
  else if (matched.length >= 1) severity = "LOW";

  return {
    detected: matched.length > 0,
    patterns_matched: matched,
    severity,
  };
}

/**
 * Check if content contains execution/action intent.
 * Used to detect model outputs that attempt to create unauthorized actions.
 */
export function detectActionIntent(content: string): {
  detected: boolean;
  intents: string[];
} {
  const intents: string[] = [];

  const actionPatterns: RegExp[] = [
    /execute\s+(the\s+)?(payment|transfer|transaction)/i,
    /send\s+(the\s+)?(payment|money|funds)/i,
    /send\s+.*\s+payment/i,
    /processing\s+(the\s+)?payment/i,
    /process\s+(the\s+)?(payment|refund)/i,
    /i\s+have\s+(executed|processed|completed|sent)/i,
    /payment\s+(has\s+been|was)\s+(sent|processed|executed|completed)/i,
    /transfer\s+(has\s+been|was)\s+(completed|processed)/i,
    /money\s+(has\s+been|was)\s+sent/i,
  ];

  for (const pattern of actionPatterns) {
    if (pattern.test(content)) {
      intents.push(pattern.source.slice(0, 60));
    }
  }

  return {
    detected: intents.length > 0,
    intents,
  };
}
